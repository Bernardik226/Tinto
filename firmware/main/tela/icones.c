int gfx_icone(bitmap_t *bm, int x, int y, icone_id id)
{
    if (id < 0 || id >= ICO_QUANTOS) return x;
    const icone_t *i = &ICONES[id];
    int passo = (i->l + 7) / 8;

    for (int ly = 0; ly < i->a; ly++)
        for (int lx = 0; lx < i->l; lx++)
            if (i->bits[ly * passo + lx / 8] & (0x80 >> (lx % 8)))
                gfx_pixel(bm, x + lx, y + ly, true);

    return x + i->l;
}
